import os
import re
import glob
from multiprocessing import get_context

INPUT_DIR = "/content"
OUTPUT_DIR = "/content/output"
PATTERN = "book_*.txt"
NUM_REDUCERS = 2

def tokenize(line):
    return re.findall(r"[^\W_]+", line.lower())


def partitioner(word):
    if word[0] in "abcdef":
        return 0
    return 1


def map_task(file_path):
    pairs = []
    with open(file_path, encoding="utf-8") as f:
        for line in f:
            for word in tokenize(line):
                pairs.append((word, 1))

    local_counts = {}
    for word, one in pairs:
        if word in local_counts:
            local_counts[word] += one
        else:
            local_counts[word] = one

    partitions = [[] for _ in range(NUM_REDUCERS)]
    for word, count in local_counts.items():
        partitions[partitioner(word)].append((word, count))

    return partitions

def shuffle_and_sort(pair_lists):
    grouped = {}
    for pairs in pair_lists:
        for word, count in pairs:
            if word not in grouped:
                grouped[word] = []
            grouped[word].append(count)
    return sorted(grouped.items())


def reduce_task(grouped):
    result = []
    for word, counts in grouped:
        total = 0
        for c in counts:
            total += c
        result.append((word, total))
    return result


def main(input_dir=INPUT_DIR, output_dir=OUTPUT_DIR, pattern=PATTERN):
    files = sorted(glob.glob(os.path.join(input_dir, pattern)))
    if not files:
        print(f"No files matching {pattern} in {input_dir}. Did the upload finish?")
        return
    print(f"{len(files)} splits -> {len(files)} mappers running in parallel")

    with get_context("fork").Pool(processes=len(files)) as pool:
        all_partitions = pool.map(map_task, files)

    os.makedirs(output_dir, exist_ok=True)
    for r in range(NUM_REDUCERS):
        incoming = [partitions[r] for partitions in all_partitions]
        grouped = shuffle_and_sort(incoming)
        result = reduce_task(grouped)

        out_path = os.path.join(output_dir, f"part-{r:05d}")
        with open(out_path, "w", encoding="utf-8") as out:
            for word, total in result:
                out.write(f"{word} {total}\n")
        print(f"reducer {r}: {len(result)} words -> {out_path}")

    for r in range(NUM_REDUCERS):
        out_path = os.path.join(output_dir, f"part-{r:05d}")
        print(f"\n===== {out_path} =====")
        print(open(out_path, encoding="utf-8").read())


main()