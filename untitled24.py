import os
import re
from collections import defaultdict

def word_count_mapper(file_path):
    word_pairs = []
    with open(file_path, 'r', encoding='utf-8') as f:
        text = f.read().lower()
        words = re.findall(r'\b\w+\b', text)
        for word in words:
            word_pairs.append((word, 1))
    return word_pairs

def word_count_reducer(mapped_values):
    word_counts = defaultdict(int)
    for word, count in mapped_values:
        word_counts[word] += count
    return dict(word_counts)

def get_top_k_words(word_counts, k=10):
    sorted_words = sorted(word_counts.items(), key=lambda item: item[1], reverse=True)
    return sorted_words[:k]

def inverted_index_mapper(file_path):
    file_name = os.path.basename(file_path)
    index_pairs = []
    with open(file_path, 'r', encoding='utf-8') as f:
        text = f.read().lower()
        words = set(re.findall(r'\b\w+\b', text))
        for word in words:
            index_pairs.append((word, file_name))
    return index_pairs

def inverted_index_reducer(mapped_values):
    inverted_index = defaultdict(set)
    for word, file_name in mapped_values:
        inverted_index[word].add(file_name)
    return {word: sorted(list(files)) for word, files in inverted_index.items()}

if __name__ == "__main__":
    dataset_dir = "Big-Data-Analytics/datasets/text-files"

    if os.path.exists(dataset_dir):
        file_paths = [
            os.path.join(dataset_dir, f)
            for f in os.listdir(dataset_dir)
            if f.startswith("book_") and f.endswith(".txt")
        ]
    else:
        file_paths = []

    print(f"Found {len(file_paths)} book files for processing.\n")

    all_word_pairs = []
    for path in file_paths:
        all_word_pairs.extend(word_count_mapper(path))
    wc_results = word_count_reducer(all_word_pairs)

    top_10 = get_top_k_words(wc_results, k=10)

    all_index_pairs = []
    for path in file_paths:
        all_index_pairs.extend(inverted_index_mapper(path))
    inv_index_results = inverted_index_reducer(all_index_pairs)

    print("--- 1. Word Count Sample ---")
    for word, count in list(wc_results.items())[:5]:
        print(f" '{word}': {count}")

    print("\n--- 2. Top 10 Most Frequent Words ---")
    for rank, (word, count) in enumerate(top_10, 1):
        print(f" {rank}. '{word}': {count}")

    print("\n--- 3. Inverted Index Sample ---")
    for word, files in list(inv_index_results.items())[:5]:
        print(f" '{word}': {files}")